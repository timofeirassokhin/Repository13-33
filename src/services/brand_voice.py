def channel_default_tone(channel_code: str) -> str:
    """Дефолтный тон по правилам бренда."""
    if channel_code in ("site", "dzen"):
        return "1"  # серьёзный для лонгридов
    return "2"  # живой для быстрых каналов


def build_draft_prompt(
    idea_description: str,
    channel_code: str,
    channel_handle: str,
    tone: str,
    direction_name: str | None = None,
    topic_name: str | None = None,
) -> str:
    """Собирает user-prompt для генерации Draft."""
    rules = CHANNEL_RULES.get(channel_code, CHANNEL_RULES["tg"])
    parts = [
        f"## Канал\n{rules['name']} ({channel_handle})\n{rules['format_hint']}",
        f"## Тон\nТон {tone} ({'Душевный' if tone == '1' else 'Живой'})",
    ]
    if direction_name:
        parts.append(f"## Направление\n{direction_name}")
    if topic_name:
        parts.append(f"## Тема\n{topic_name}")
    parts.append(f"## Исходная идея\n{idea_description}")
    parts.append(
        "## Задача\nНапиши пост по этой идее, под этот канал, в указанном тоне. "
        "Не превышай char_limit канала. Не используй markdown-заголовки если канал — Telegram, "
        "Facebook, VK или X (только сайт и Дзен — длинный формат). Ответь ТОЛЬКО текстом поста, "
        "без предисловий и комментариев."
    )
    return "\n\n".join(parts)
