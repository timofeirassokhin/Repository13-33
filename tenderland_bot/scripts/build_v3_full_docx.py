def shade(cell, hexc: str):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), hexc)
    tcPr.append(sh)


def thin_borders(table):
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), "BFBFBF")
        borders.append(e)
    tblPr.append(borders)


def codebox(doc, label: str, text: str, fillhex: str, monosize=7.5):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = t.cell(0, 0)
    shade(cell, fillhex)
    cell.width = Cm(17)
    p = cell.paragraphs[0]
    if label:
        lr = p.add_run(label + "\n")
        lr.bold = True
        lr.font.size = Pt(9)
    run = p.add_run(text)
    run.font.name = "Consolas"
    run.font.size = Pt(monosize)
    thin_borders(t)
    doc.add_paragraph()


def kv_table(doc, header, rows, style="Light Grid Accent 1"):
    tbl = doc.add_table(rows=1, cols=len(header))
    tbl.style = style
    for i, h in enumerate(header):
        tbl.rows[0].cells[i].paragraphs[0].add_run(h).bold = True
    for r in rows:
        cells = tbl.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = str(v)


